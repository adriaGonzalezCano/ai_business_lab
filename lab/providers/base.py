"""Provider interface. Business logic only ever talks to this."""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, Protocol


class ProviderError(RuntimeError):
    """Transient or remote failure; the call may have cost money if tokens are reported."""


class ProviderUnavailable(RuntimeError):
    """Provider is not configured (missing key etc.). No call was made."""


@dataclass
class ProviderRequest:
    model: str
    system: str
    prompt: str
    max_tokens: int
    task: str
    # Structured, trusted context for deterministic providers (the real providers ignore it).
    context: dict[str, Any] = field(default_factory=dict)


@dataclass
class ProviderResult:
    text: str
    input_tokens: int
    output_tokens: int
    actual_cost: float | None = None  # only if the provider reports a cost


class Provider(Protocol):
    name: str
    synthetic: bool  # True => output is generated by a stand-in, never real analysis

    def available(self) -> tuple[bool, str]:
        """(ok, reason). reason explains how to configure it when not ok."""

    def complete(self, req: ProviderRequest) -> ProviderResult: ...
